// TestBuiltinOutbound：内置的 outbound 规则每种形状一条（spec §6.2），按类别分组，作用于提示词与工具输出，
// 默认启用（类别的开关在配置里，PII 类别默认关闭）；credentials.high_entropy 默认停用，只用于遮蔽（维护者决定
// 2026-10-16）。
func TestBuiltinOutbound(t *testing.T) {
	s := builtinSet(t)
	got := map[string]string{}
	for _, r := range s.Outbound() {
		got[r.ID] = r.Category
		if r.Enabled() != (r.ID != "credentials.high_entropy") || !r.AppliesTo(guard.EventPrompt) || !r.AppliesTo(guard.EventToolOutput) || !r.Builtin {
			t.Errorf("%s = %+v", r.ID, r)
		}
	}
	want := map[string]string{
		"credentials.prefixed_token": "credentials", "credentials.bearer": "credentials", "credentials.assignment": "credentials",
		"credentials.aws_access_key": "credentials", "credentials.url_password": "credentials", "credentials.high_entropy": "credentials",
		"private_key.pem": "private_key",
		"pii.email":       "pii", "pii.phone_cn": "pii", "pii.phone_intl": "pii", "pii.cn_id": "pii", "pii.us_ssn": "pii", "pii.ip": "pii",
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("outbound rules = %v", got)
	}
	// outbound 规则不出现在 action 规则里
	for _, r := range s.All() {
		if strings.Contains(r.ID, ".") {
			t.Errorf("action rule %s", r.ID)
		}
	}
}

// TestBuiltinOutboundExamples：每条内置 outbound 规则都有样例；hit 必须命中，miss 必须不命中。
func TestBuiltinOutboundExamples(t *testing.T) {
	for _, r := range builtinSet(t).Outbound() {
		if len(r.Examples.Hit) == 0 || len(r.Examples.Miss) == 0 {
			t.Errorf("%s has no hit or miss examples", r.ID)
			continue
		}
		for _, text := range r.Examples.Hit {
			if locs, _, err := r.Find(context.Background(), text); err != nil || len(locs) == 0 {
				t.Errorf("%s: hit example %q not matched (%v)", r.ID, text, err)
			}
		}
		for _, text := range r.Examples.Miss {
			if locs, _, err := r.Find(context.Background(), text); err != nil || len(locs) != 0 {
				t.Errorf("%s: miss example %q matched %v (%v)", r.ID, text, locs, err)
			}
		}
	}
}

// TestDetectorsTogether：同一段文本里几条检测器规则一起查时，重叠的片段只报最具体的一条（带 +86 的号码只报
// pii.phone_cn）；只启用一部分时在启用的里面取。
func TestDetectorsTogether(t *testing.T) {
	text := "call +86 13800138000 or mail alice.wang@acme-corp.cn, key sk-abcdefghijklmnop1234"
	got := rules.FindDetectors(text, []string{"pii.phone_cn", "pii.phone_intl", "pii.email", "credentials.prefixed_token"})
	want := map[string][][2]int{
		"pii.phone_cn":               {{5, 20}},
		"pii.email":                  {{29, 52}},
		"credentials.prefixed_token": {{58, 81}},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("got %v", got)
	}
	if got := rules.FindDetectors(text, []string{"pii.phone_intl"}); !reflect.DeepEqual(got, map[string][][2]int{"pii.phone_intl": {{5, 20}}}) {
		t.Errorf("phone_intl only: %v", got)
	}
}

// TestDetectorsConfirm：拦截用的检测器只认像真的凭据的值：开发提示词里常见的占位符、代码表达式、由单词拼成的写法、
// 路径与标识符都不算（M4a 计划评审 C2、I1）；停用一条凭据规则不会吞掉另一条启用规则的命中（I2）。
func TestDetectorsConfirm(t *testing.T) {
	all := []string{"credentials.prefixed_token", "credentials.bearer", "credentials.assignment", "credentials.aws_access_key",
		"credentials.url_password", "credentials.high_entropy", "private_key.pem"}
	for _, text := range []string{
		"Bearer authentication uses the AuthorizationHeaderProvider",
		"git checkout pk_feature_branch_for_payments && pip install sk-learn-preprocessing-module",
		"why does token = jwt.encode(payload, key) fail?",
		`token = request.headers.get("X-Token")`,
		`password = os.environ["DB_PASSWORD"]`,
		"API_KEY=your-api-key-here\npassword: changeme\nSECRET_KEY=<generate one>\nTOKEN=${GITHUB_TOKEN}\napi_key: xxxxxxxxxxxx",
		"DATABASE_URL=postgres://user:password@localhost:5432/dev",
		"Fix the token refresh bug in src/main/java/com/acme/OAuth2TokenService",
		"the token is generated by generateHmacSha256TokenForUser",
		"the access key policy is AWSLambdaBasicExecutionRole2",
		"password = getpass.getpass()",
	} {
		if got := rules.FindDetectors(text, all); len(got) != 0 {
			t.Errorf("%q: %v", text, got)
		}
	}
	text := "OPENAI_API_KEY=sk-proj-Ab3dEf6hIj9kLm2nOp5q"
	if got := rules.FindDetectors(text, []string{"credentials.assignment"}); len(got["credentials.assignment"]) != 1 {
		t.Errorf("prefixed_token disabled: %v", got)
	}
}

// cancelAfter 在第 n 次 Err 调用起返回 context.Canceled（只改 Err，用来在匹配之间确定地取消）。
type cancelAfter struct {
	context.Context
	n, calls int
}

func (c *cancelAfter) Err() error {
	if c.calls++; c.calls >= c.n {
		return context.Canceled
	}
	return nil
}

// TestFindReportsCancel：扫描途中被取消时返回已找到的命中，同时报告取消，不把没扫完当成扫完（M4a Codex 第二轮
// R2-01）。最后一个正则、第一处匹配之后取消也一样。
func TestFindReportsCancel(t *testing.T) {
	dir := t.TempDir()
	os.WriteFile(filepath.Join(dir, "k.yaml"), []byte("schema: 1\nid: acme.key\ncategory: credentials\non: [prompt]\nmatch: {regex: ['ACME-[0-9]{12}']}\n"), 0o600)
	s, err := rules.Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	r := s.GetOutbound("acme.key")
	text := "ACME-111111111111 ACME-222222222222"
	if locs, timedOut, err := r.Find(context.Background(), text); err != nil || timedOut || len(locs) != 2 {
		t.Fatalf("complete: %v %v %v", locs, timedOut, err)
	}
	locs, _, err := r.Find(&cancelAfter{Context: context.Background(), n: 2}, text)
	if !errors.Is(err, context.Canceled) || !reflect.DeepEqual(locs, [][2]int{{0, 17}}) {
		t.Errorf("cancelled after the first match: %v %v", locs, err)
	}
}

// TestUserOutboundRule：用户规则包给自定义类别加本地规则（spec §6.1 的例子）：正则不区分大小写，按 id 覆盖开关。
func TestUserOutboundRule(t *testing.T) {
	dir := t.TempDir()
	os.WriteFile(filepath.Join(dir, "falcon.yaml"), []byte("schema: 1\nid: acme.codename\ncategory: acme-codename\non: [prompt, tool_output]\n"+
		"match:\n  regex: ['\\bProject Falcon\\b']\nexamples:\n  hit: ['status of project falcon?']\n  miss: ['falconry club']\n"), 0o600)
	s, err := rules.Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	r := s.GetOutbound("acme.codename")
	if r == nil || r.Category != "acme-codename" || r.Builtin {
		t.Fatalf("rule = %+v", r)
	}
	locs, timedOut, err := r.Find(context.Background(), "line one\nwhere is Project Falcon now")
	if err != nil || timedOut || !reflect.DeepEqual(locs, [][2]int{{18, 32}}) {
		t.Errorf("Find = %v %v %v", locs, timedOut, err)
	}
	// 多字节文本：regexp2 按字符计位置，返回的区间是字节偏移（行号与摘录按字节切）
	if locs, _, err := r.Find(context.Background(), "第一行说明\n项目 Project Falcon 的进展"); err != nil || !reflect.DeepEqual(locs, [][2]int{{23, 37}}) {
		t.Errorf("multibyte Find = %v %v", locs, err)
	}
	if _, err := s.Apply(rules.Overrides{"acme.codename": false, "pii.email": false}); err != nil {
		t.Fatal(err)
	}
	if s.GetOutbound("acme.codename").Enabled() || s.GetOutbound("pii.email").Enabled() {
		t.Error("overrides not applied")
	}
	if _, err := s.Apply(rules.Overrides{"pii.nope": false}); err == nil {
		t.Error("unknown id accepted")
	}
}

// TestOutboundRuleErrors：outbound 规则的写法错误都在加载时报出；错误说明不回显写下的正则。
func TestOutboundRuleErrors(t *testing.T) {
	base := "schema: 1\nid: x.rule\ncategory: x-cat\non: [prompt]\n"
	for name, c := range map[string]struct{ yaml, path string }{
		"no category":          {"schema: 1\nid: x.rule\non: [prompt]\nmatch: {regex: [a]}\n", ""},
		"bad category":         {"schema: 1\nid: x.rule\ncategory: 'X Cat'\non: [prompt]\nmatch: {regex: [a]}\n", "category"},
		"action kind in on":    {"schema: 1\nid: x.rule\ncategory: x-cat\non: [exec]\nmatch: {regex: [a]}\n", "on"},
		"no on":                {"schema: 1\nid: x.rule\ncategory: x-cat\nmatch: {regex: [a]}\n", "on"},
		"no match":             {base, "match"},
		"regex and detector":   {base + "match: {regex: [a], detector: pii.email}\n", "match"},
		"unknown detector":     {base + "match: {detector: pii.nope}\n", "match.detector"},
		"bad regex":            {base + "match: {regex: ['(secret-shape']}\n", "match.regex[0]"},
		"action on the rule":   {base + "action: deny\nmatch: {regex: [a]}\n", "action"},
		"question on the rule": {base + "question: {kind: probability, instructions: {question: q}}\nmatch: {regex: [a]}\n", "question"},
		"locked":               {base + "locked: true\nmatch: {regex: [a]}\n", "locked"},
	} {
		dir := t.TempDir()
		os.WriteFile(filepath.Join(dir, "r.yaml"), []byte(c.yaml), 0o600)
		_, err := rules.Load(dir)
		var re *rules.Error
		if err == nil || !strings.Contains(err.Error(), "x") {
			t.Errorf("%s: err = %v", name, err)
			continue
		}
		if c.path != "" && (!errors.As(err, &re) || re.Path != c.path) {
			t.Errorf("%s: path = %v", name, err)
		}
		if strings.Contains(err.Error(), "secret-shape") {
			t.Errorf("%s: error echoes the regex: %v", name, err)
		}
	}
}

